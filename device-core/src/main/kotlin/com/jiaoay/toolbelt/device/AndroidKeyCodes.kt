    /** 全表条目数：数据完整性断言锚（官方公开常量全集增删须同步本值与全表） */
    const val TOTAL_COUNT = 338

    /** 按键值查（null = 全表无此键值） */
    fun byCode(code: Int): AndroidKeyCode? = ALL.firstOrNull { it.code == code }

    /** 按常量名查（精确名，忽略大小写；null = 全表无此常量名） */
    fun byName(name: String): AndroidKeyCode? = ALL.firstOrNull { it.name.equals(name, ignoreCase = true) }

    /** 查询命中集（过滤纯函数，语义见类头注释；命中序 = 键值升序） */
    fun matches(query: String): List<AndroidKeyCode> {
        val q = query.trim()
        if (q.isEmpty()) return emptyList()
        // 纯数字（含全角正整数不迁就——十进制 ASCII 直收域同 customKey）
        return if (q.toIntOrNull() != null) {
            ALL.filter { it.code.toString().startsWith(q) }
        } else {
            ALL.filter { it.name.contains(q, ignoreCase = true) }
        }
    }
