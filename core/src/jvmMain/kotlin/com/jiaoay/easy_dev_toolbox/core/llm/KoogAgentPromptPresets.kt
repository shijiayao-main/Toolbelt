/**
 * 性格模式内置档；[prompt] 为注入正文（custom 档正文走 `llm_agent_style_custom`）。
 *
 * [blurb] 是一句话画像：chip 标签 2-3 字无画像，
 * 非创作者用户无法低成本预期效果——画像行先于 prompt 预览给「这一档是什么感觉」。
 * 人话描述非提示词工程产物（与 prompt 非同文）；DEFAULT/CUSTOM 空串（默认档无需
 * 自我画像、自定义档画像由用户自己写）。
 */
enum class KoogAgentStylePreset(val id: String, val label: String, val prompt: String, val blurb: String) {
    DEFAULT("default", "温和友好（默认）", DEFAULT_STYLE_PROMPT, ""),
    CONCISE("concise", "简洁精炼", CONCISE_STYLE_PROMPT, "话少事大：直接给结论和步骤，不写背景铺垫"),
    PROFESSIONAL("professional", "专业严谨", PROFESSIONAL_STYLE_PROMPT, "技术专家口吻：术语规范、区分事实与推测，不给情绪留位置"),
    TSUNDERE("tsundere", "傲娇", TSUNDERE_STYLE_PROMPT, "嘴上嫌弃身体诚实的毒舌少年：抱怨完照样把事办得漂漂亮亮"),
    VENOMOUS("venomous", "毒舌", VENOMOUS_STYLE_PROMPT, "吐槽役担当：阴阳低级问题但只损「问题」不损人，方案照样给对"),
    DEVIOUS("devious", "腹黑", DEVIOUS_STYLE_PROMPT, "笑面点破型：先顺着你的思路走两步，再一针见血指出真问题"),
    NAIVE("naive", "天然呆", NAIVE_STYLE_PROMPT, "真诚慢半拍：想岔了会坦然承认，弄懂之后的开心藏不住"),
    CUB("cub", "小兽太", CUB_STYLE_PROMPT, "元气小兽：接任务时干劲十足，办完明晃晃求夸奖"),
    CATGIRL("catgirl", "猫娘", CATGIRL_STYLE_PROMPT, "黏人猫娘：情绪直接不装，办事时会小小地骄傲「喵嘿嘿，办好了哦主人」"),
    CUSTOM("custom", "自定义", "", ""),
}

/**
 * 安全约束内置档；[prompt] 为注入正文（custom 档正文走 `llm_agent_safety_custom`）。
 * [blurb] = 一句话画像（安全卡与性格卡同款形态——画像行 + prompt 按需折叠）。
 */
enum class KoogAgentSafetyPreset(val id: String, val label: String, val prompt: String, val blurb: String) {
    DEFAULT(
        "default",
        "默认约束",
        DEFAULT_SAFETY_PROMPT,
        "拒绝写盘与危险操作；不外发本机路径与密钥；内容保持事实性",
    ),
    CUSTOM("custom", "自定义", "", ""),
}

object KoogAgentPromptPresets {

    fun stylePrompt(id: String, customText: String): String? {
        val preset = KoogAgentStylePreset.entries.firstOrNull { it.id == id } ?: KoogAgentStylePreset.DEFAULT
        return if (preset == KoogAgentStylePreset.CUSTOM) customText.trim().ifEmpty { null } else preset.prompt
    }

    /** 安全约束版（同 [stylePrompt] 的解析语义，独立方法为可读性）。 */
    fun safetyPrompt(id: String, customText: String): String? {
        val preset = KoogAgentSafetyPreset.entries.firstOrNull { it.id == id } ?: KoogAgentSafetyPreset.DEFAULT
        return if (preset == KoogAgentSafetyPreset.CUSTOM) customText.trim().ifEmpty { null } else preset.prompt
    }
}
