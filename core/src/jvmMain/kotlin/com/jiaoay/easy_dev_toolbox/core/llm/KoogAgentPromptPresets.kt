package com.jiaoay.easy_dev_toolbox.core.llm

/**
 * Koog 调度 agent 的内置提示词档（性格模式 + 安全约束可配置化，共 10 档）：
 *
 * - **性格模式**（[KoogAgentStylePreset]）：output style 等价物——决定飞书机器人轻量回复的
 *   语气与风格。
 * - **安全约束**（[KoogAgentSafetyPreset]）：注入提示词**末尾**的不可违反约束（头部字面量
 *   `[安全约束 - 不可违反]` 与 CLI 后端 `safetyPromptSuffix` 同源对齐）。
 *
 * 作用范围：仅 Koog 调度 agent 的轻量回复；**不透传被委托
 *    CLI**（CLI 有自己的 safetyPromptSuffix——同域语义分界）。
 * 性格仅对外输出位置注入（显式纪律）：飞书调度链
 *    （KoogAgentRunner.buildKoogSystemPrompt）是**全仓唯一**性格注入链——内部执行链
 *    （工作台/蒸馏/语音/Quest 流程域/MCP/CLI）system prompt 一律零性格段（任务域
 *    指令纯认知层，减 token 消耗）；新会话域按此纪律零注入。
 *
 * 归属 `:core`（两 feature 的合规公共域）：`KoogAgentRunner`（:feature-larkbridge）与 AI 设置页
 * （:feature-ai）各自 import 本包——feature→core 向下依赖，UiGuard 放行。
 *
 * UI 消费形态：`entries.map { it.id }` 作 options、`associate { it.id to it.label }` 作 labels；
 * 内置档正文对用户**只读可复制**（不支持编辑——便于参考后自写 custom 档）。
 *
 * 10 档正文统一四段结构（防漂移锚见 KoogAgentPromptPresetsTest）：
 * 【性格定义】心理年龄/真实流露/情绪基调 →【表达方式】语境化语气词不机械 →
 * 【优先级约束】回复结构规范优先于语气 +「正经点」收口 →【技术内容纪律】代码/报错工程化、
 * 人格不侵蚀准确性。
 */

