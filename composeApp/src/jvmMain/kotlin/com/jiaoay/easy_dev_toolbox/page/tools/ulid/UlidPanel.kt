/**
 * ULID 面板：「工具」聚合页子签内容体（聚合页原生签——无 palette 深入模式候选、
 * 无持久化，全部状态会话内）。
 *
 * 两段：生成（数量输入 + 批量生成，逐行/整批复制）与解析（粘贴 ULID → 内嵌
 * 48 位毫秒时间戳反解人类时间 + 80 位随机部分 hex 展开——日志关联排查时把
 * 主键/链路标识反解出生成时间）。
 *
 * 视觉层（批量结果行密度、解析结果行排布）为保守默认，待真机终裁。
 */
@Composable
fun UlidPanel() {
    UlidGenerateSection()
    UlidParseSection()
}

@Composable
private fun UlidGenerateSection() {
    var countText by remember { mutableStateOf("1") }
    var generated by remember { mutableStateOf<List<String>>(emptyList()) }

    val count = countText.trim().toIntOrNull()
    val countValid = count != null && count in 1..MAX_ULID_GENERATE_COUNT

    SectionCard(
        title = "ULID 生成",
        description = "48 位毫秒时间戳 + 80 位加密强随机——同一毫秒内多次生成不保证有序（规格单调性为可选项）",
        headerTrailing = {
            PillLabel(
                text = "Crockford Base32 · 26 位",
                container = LocalToolboxSurfaceColors.current.surfaceDeep,
                contentColor = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        },
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(Dimens.space8),
        ) {
            OutlinedTextField(
                value = countText,
                onValueChange = { countText = it },
                label = { Text("生成数量（1..$MAX_ULID_GENERATE_COUNT）") },
                singleLine = true,
                textStyle = DesktopTypography.monoInput,
            )
            AppButton(
                label = "生成",
                busy = false,
                enabled = countValid,
                onClick = {
                    val n = count
                    if (n != null && n in 1..MAX_ULID_GENERATE_COUNT) {
                        generated = generateUlids(n)
                    }
                },
            )
        }
        if (countText.isNotBlank() && !countValid) {
            Text(
                text = "数量须为 1..$MAX_ULID_GENERATE_COUNT 的整数",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.error,
            )
        }
        if (generated.isNotEmpty()) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(Dimens.space8),
            ) {
                Text(
                    text = "已生成 ${generated.size} 个",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                CopyIconButton(
                    textProvider = { generated.joinToString("\n") },
                    contentDescription = "复制全部 ULID",
                )
            }
            Column(verticalArrangement = Arrangement.spacedBy(Dimens.space4)) {
                generated.forEach { ulid ->
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(Dimens.space8),
                    ) {
                        Text(
                            text = ulid,
                            style = DesktopTypography.mono,
                            color = MaterialTheme.colorScheme.onSurface,
                            modifier = Modifier.weight(1f),
                        )
                        CopyIconButton(
                            textProvider = { ulid },
                            contentDescription = "复制该 ULID",
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun UlidParseSection() {
    var input by remember { mutableStateOf("") }

    val result = remember(input) { parseUlid(input) }

    SectionCard(
        title = "ULID 解析",
        description = "粘贴 ULID → 内嵌时间戳反解人类时间 + 随机部分展开；大小写不敏感",
        headerTrailing = {
            PillLabel(
                text = "时间戳反解 · 只解不验",
                container = LocalToolboxSurfaceColors.current.surfaceDeep,
                contentColor = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        },
    ) {
        OutlinedTextField(
            value = input,
            onValueChange = { input = it },
            label = { Text("ULID 文本") },
            placeholder = { Text("26 位标准形态（本地主键 / 链路标识，粘贴进来反解生成时间）") },
            singleLine = true,
            modifier = Modifier.fillMaxWidth(),
            textStyle = DesktopTypography.monoInput,
        )
        when (val decoded = result) {
            is UlidParseResult.Empty -> Unit

            is UlidParseResult.Invalid -> Text(
                text = decoded.reason,
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.error,
            )

            is UlidParseResult.Ok -> {
                ParseResultRow(label = "时间戳（毫秒）", value = decoded.timestampMillis.toString())
                ParseResultRow(label = "生成时间", value = decoded.humanTime)
                ParseResultRow(label = "随机部分（hex）", value = decoded.randomHex)
                ParseResultRow(label = "标准形态（大写）", value = decoded.canonical)
            }
        }
    }
}

/** 解析结果行：字段名 + 值 + 行尾复制钮（「反解出来 → 带走比对」动线） */
@Composable
private fun ParseResultRow(label: String, value: String) {
    Row(
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(Dimens.space8),
    ) {
        Text(
            text = label,
            style = DesktopTypography.monoTag,
            color = MaterialTheme.colorScheme.primary,
        )
        Text(
            text = value,
            style = DesktopTypography.mono,
            color = MaterialTheme.colorScheme.onSurface,
            modifier = Modifier.weight(1f),
        )
        CopyIconButton(
            textProvider = { value },
            contentDescription = "复制$label",
        )
    }
}
